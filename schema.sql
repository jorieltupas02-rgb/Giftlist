-- GiftList database setup for Supabase
-- Run this whole script in Supabase Dashboard > SQL Editor > New query.
create table if not exists public.gifts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 120),
  recipient text not null check (char_length(trim(recipient)) between 1 and 120),
  occasion text not null,
  price numeric(12,2) check (price is null or price >= 0),
  notes text not null default '',
  purchased boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.gifts enable row level security;

drop policy if exists "Users can view their own gifts" on public.gifts;
create policy "Users can view their own gifts"
on public.gifts for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Users can add their own gifts" on public.gifts;
create policy "Users can add their own gifts"
on public.gifts for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own gifts" on public.gifts;
create policy "Users can update their own gifts"
on public.gifts for update to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own gifts" on public.gifts;
create policy "Users can delete their own gifts"
on public.gifts for delete to authenticated
using (auth.uid() = user_id);

create index if not exists gifts_user_id_created_at_idx
on public.gifts (user_id, created_at desc);
